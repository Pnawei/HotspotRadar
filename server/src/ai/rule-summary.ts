// 规则摘要生成器 - 无 AI Key 或调用失败时的降级方案
// 根据标题关键词生成丰富具体的摘要（保留原有实现）

export function ruleSummary(title: string): string {
  const cleanTitle = title.replace(/[#【】[\]《》「」『』""]/g, '');

  const keywords = {
    entertainment: ['明星', '演员', '歌手', '导演', '电影', '电视剧', '综艺', '官宣', '恋情', '分手', '结婚', '离婚', '演唱会', '粉丝', '代言', '新剧', '票房', '颁奖', '热搜', '上映', '定档', '路透', '杀青', '开机'],
    technology: ['AI', '人工智能', '手机', '芯片', '5G', '6G', '新能源', '电动车', '发布', '研发', '突破', '技术', '互联网', '软件', '系统', '华为', '苹果', '特斯拉', '小米', '量子', '机器人', '算法', '数据', '云计算'],
    finance: ['股市', '股票', '基金', '房价', '利率', '央行', '银行', '降息', '降准', '投资', 'IPO', '上市', '财报', '营收', '利润', '市值', '涨停', '跌停', '牛市', '熊市', '期货', '外汇'],
    social: ['教育', '医疗', '高考', '考研', '就业', '政策', '交通', '天气', '地震', '台风', '安全', '事故', '救援', '公益', '养老', '生育', '医保', '社保', '退休', '房租'],
    international: ['美国', '俄罗斯', '欧洲', '日本', '韩国', '中东', '战争', '冲突', '外交', '访问', '峰会', '制裁', '贸易', '谈判', '朝鲜', '印度', '英国', '法国', '德国'],
    sports: ['冠军', '比赛', '联赛', '世界杯', '奥运', '金牌', '球星', '转会', '教练', '足球', '篮球', '网球', 'NBA', '欧冠', '亚冠', '中超', '马拉松'],
  };

  let category = 'general';
  for (const [cat, words] of Object.entries(keywords)) {
    if (words.some((word) => cleanTitle.includes(word))) {
      category = cat;
      break;
    }
  }

  const numbers = cleanTitle.match(/\d+[万亿%度]?/g) || [];
  const hasNumber = numbers.length > 0;

  const summaryGenerators: Record<string, (t: string) => string> = {
    entertainment: (t) => {
      if (t.includes('官宣') || t.includes('恋情'))
        return `娱乐圈重磅爆料！「${t}」消息传出后迅速登顶热搜，相关话题阅读量已超10亿。多家媒体跟进报道，粉丝们在评论区送上祝福，但也有网友表示"意难平"。业内人士分析，这一消息将对当事人的商业代言和未来作品产生影响。`;
      if (t.includes('电影') || t.includes('票房'))
        return `影视行业最新战报！「${t}」${hasNumber ? `，${numbers[0]}的成绩令业界瞩目` : ''}。分析师指出，这一表现反映了观众对优质内容的持续追捧，也预示着电影市场的强劲复苏。目前该片在各大购票平台评分均超过9分，口碑持续发酵。`;
      if (t.includes('演唱会'))
        return `演唱会市场火爆！「${t}」的消息一出，粉丝们彻夜排队抢票。据统计，门票在开售后${hasNumber ? numbers[0] : '数分钟'}内售罄，二手市场价格已翻数倍。主办方正在评估加场可能性，预计将带动周边城市旅游消费。`;
      return `娱乐热点追踪：「${t}」引发全网热议，相关话题占据多个平台热搜榜首。网友们在评论区展开激烈讨论，明星工作室和经纪公司暂未对此作出回应。业内预计事件将持续发酵24-48小时。`;
    },
    technology: (t) => {
      if (t.includes('发布') || t.includes('推出'))
        return `科技行业重磅发布！「${t}」${hasNumber ? `，${numbers[0]}的参数指标创下新纪录` : ''}。分析师认为，此举将重塑行业竞争格局，对上下游产业链产生深远影响。投资者反应积极，相关概念股盘中大涨，后续市场表现值得关注。`;
      if (t.includes('突破') || t.includes('研发'))
        return `科研领域重大突破！「${t}」的消息引发学界和产业界强烈反响。专家表示，这一进展具有里程碑意义，有望在未来3-5年内实现商业化应用。多家投资机构已表达合作意向，资本市场反应热烈。`;
      if (t.includes('AI') || t.includes('人工智能'))
        return `AI领域再掀波澜！「${t}」${hasNumber ? `，性能提升达${numbers[0]}` : ''}。业内专家分析，这标志着人工智能技术进入新的发展阶段。各大科技公司正加速布局，人才争夺战愈发激烈，行业变革或将加速到来。`;
      return `科技前沿动态：「${t}」成为业界焦点。技术专家认为，这一发展趋势将深刻影响未来5-10年的产业格局。建议投资者和从业者密切关注相关进展，把握技术变革带来的机遇。`;
    },
    finance: (t) => {
      if (t.includes('央行') || t.includes('利率'))
        return `金融市场重大信号！「${t}」${hasNumber ? `，幅度达${numbers[0]}` : ''}。经济学家解读，此举旨在优化货币政策传导机制，预计将释放大量流动性，有效降低实体经济融资成本。市场各方正密切关注政策细节和后续影响。`;
      if (t.includes('股市') || t.includes('股票'))
        return `资本市场最新动态！「${t}」${hasNumber ? `，涨幅达${numbers[0]}` : ''}。市场分析人士指出，多重利好因素共振推动行情走强，但投资者仍需关注政策面和基本面变化，理性看待市场波动，做好风险管理。`;
      return `财经要闻聚焦：「${t}」引发市场广泛关注。业内分析认为，这一动向反映了当前宏观经济形势的最新变化，建议投资者保持理性，关注政策走向和市场基本面。`;
    },
    social: (t) => {
      if (t.includes('政策'))
        return `重磅政策出台！「${t}」的消息发布后，迅速引发社会各界广泛关注。政策解读专家表示，此举将直接惠及广大民众，预计覆盖${hasNumber ? numbers[0] : '数千万'}人群。具体实施细则有待进一步公布。`;
      if (t.includes('天气') || t.includes('降温'))
        return `天气预警提醒！「${t}」${hasNumber ? `，降温幅度达${numbers[0]}` : ''}。气象部门已发布相关预警，提醒市民做好防寒保暖措施，合理安排出行计划。各地应急管理部门已启动预案，确保供暖和交通安全。`;
      return `社会热点关注：「${t}」成为近期焦点话题。事件涉及公众切身利益，引发网友热烈讨论。相关部门高度重视，正在积极研究解决方案，后续进展值得持续关注。`;
    },
    international: (t) => {
      if (t.includes('访问') || t.includes('会谈'))
        return `国际外交重要动态！「${t}」引发全球媒体高度关注。国际关系专家分析，此次互动对双边关系发展具有重要战略意义，释放出积极的合作信号。各方预计将在经贸、安全等领域达成新共识。`;
      if (t.includes('冲突') || t.includes('局势'))
        return `国际局势最新进展！「${t}」的报道引发国际社会高度关注。联合国和多国政府呼吁各方保持克制，通过对话协商解决分歧。分析人士指出，局势走向仍存在较大不确定性。`;
      return `国际热点聚焦：「${t}」成为全球舆论焦点。多国媒体从不同角度进行报道分析，国际观察家认为此事件将对地区乃至全球格局产生深远影响，值得持续跟踪关注。`;
    },
    sports: (t) => {
      if (t.includes('冠军') || t.includes('金牌'))
        return `体坛捷报传来！「${t}」的消息让亿万观众欢呼雀跃。这一历史性成绩展现了运动员的卓越实力和拼搏精神，赛后各方祝贺纷至沓来。分析认为这将极大提振国民士气和体育产业发展。`;
      return `体坛热点聚焦：「${t}」引发球迷和观众的热烈讨论。赛事精彩程度超出预期，相关话题在社交平台持续升温，各类赛事分析和评论层出不穷。后续比赛同样值得期待。`;
    },
    general: (t) => `热点事件追踪：「${t}」在多个平台引发广泛讨论，目前已有超过${hasNumber ? numbers[0] : '百万'}网友参与互动。舆论观点多元，各方声音交织，事件仍在持续发展中。建议关注官方权威信息，理性看待各方观点。`,
  };

  const generator = summaryGenerators[category] || summaryGenerators.general;
  return generator(cleanTitle);
}
